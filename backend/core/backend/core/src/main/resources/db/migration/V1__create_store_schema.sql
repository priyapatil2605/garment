CREATE TABLE products (
    product_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(150) NOT NULL,
    category VARCHAR(80) NOT NULL,
    description TEXT,
    price NUMERIC(12,2) NOT NULL CHECK (price >= 0),
    image_url TEXT,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE server_nodes (
    server_id INTEGER PRIMARY KEY,
    server_name VARCHAR(100) NOT NULL,
    host VARCHAR(255) NOT NULL,
    http_port INTEGER NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'UNKNOWN',
    role VARCHAR(20) NOT NULL DEFAULT 'REPLICA',
    last_heartbeat TIMESTAMPTZ
);

CREATE TABLE inventory (
    product_id BIGINT NOT NULL REFERENCES products(product_id),
    server_id INTEGER NOT NULL REFERENCES server_nodes(server_id),
    quantity INTEGER NOT NULL DEFAULT 0 CHECK (quantity >= 0),
    reserved_quantity INTEGER NOT NULL DEFAULT 0 CHECK (reserved_quantity >= 0),
    version BIGINT NOT NULL DEFAULT 0,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (product_id, server_id),
    CHECK (reserved_quantity <= quantity)
);

CREATE TABLE orders (
    order_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_name VARCHAR(150) NOT NULL,
    total_amount NUMERIC(12,2) NOT NULL CHECK (total_amount >= 0),
    status VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    processed_by_server INTEGER REFERENCES server_nodes(server_id),
    idempotency_key VARCHAR(100) UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE order_items (
    order_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(order_id),
    product_id BIGINT NOT NULL REFERENCES products(product_id),
    product_name VARCHAR(150) NOT NULL,
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    unit_price NUMERIC(12,2) NOT NULL CHECK (unit_price >= 0),
    line_total NUMERIC(12,2) NOT NULL CHECK (line_total >= 0)
);

CREATE TABLE replication_log (
    replication_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_server_id INTEGER REFERENCES server_nodes(server_id),
    target_server_id INTEGER REFERENCES server_nodes(server_id),
    state_version BIGINT NOT NULL,
    consistency_mode VARCHAR(30) NOT NULL,
    status VARCHAR(30) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE experiment_runs (
    run_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    experiment_number INTEGER NOT NULL CHECK (experiment_number BETWEEN 1 AND 9),
    status VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    input_data JSONB,
    result_data JSONB,
    started_at TIMESTAMPTZ,
    completed_at TIMESTAMPTZ
);

CREATE TABLE system_events (
    event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    server_id INTEGER REFERENCES server_nodes(server_id),
    event_type VARCHAR(80) NOT NULL,
    message TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_orders_created_at ON orders(created_at DESC);
CREATE INDEX idx_orders_status ON orders(status);
CREATE INDEX idx_order_items_order_id ON order_items(order_id);
CREATE INDEX idx_inventory_product_id ON inventory(product_id);
CREATE INDEX idx_replication_created_at ON replication_log(created_at DESC);
CREATE INDEX idx_experiment_runs_number ON experiment_runs(experiment_number);
